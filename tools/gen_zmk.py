#!/usr/bin/env python3
"""
Writes the ZMK matrix transform and physical layout of the mnhttn48_unibody shield.

    tools/gen_zmk.py

Reads board/layout.json (key centres in mm, KiCad rotation) and tools/matrix.json (COL/ROW of every
key) and writes zmk-config/boards/shields/mnhttn48_unibody/mnhttn48_unibody-layouts.dtsi.

Keymap order, as in the mnhTTn48 keymap: four rows of ten (left half pinky to inner, right half
inner to pinky), then the thumbs left outer, left inner, right inner, right outer. In the matrix
COL 0..7 is the key row (left half 0..3, right half 4..7) driven by the 74HC595, ROW 0..4 the finger
column (0 pinky) and ROW 5 the thumbs, read by the XIAO; RC(row, col) follows that.
Physical layout units: 1u = 18 mm (the key pitch), so a cell is 100 x 94; rotation in ZMK's
clockwise centi-degrees around the key centre.
"""

import json
from pathlib import Path

REPO = Path(__file__).resolve().parent.parent
LAYOUT = REPO / "board" / "layout.json"
MATRIX = REPO / "tools" / "matrix.json"
OUTPUT = REPO / "zmk-config" / "boards" / "shields" / "mnhttn48_unibody" / "mnhttn48_unibody-layouts.dtsi"
UNIT_MM = 18.0
CELL_W, CELL_H = 18.0, 17.0


def keymap_order(matrix):
    """Switch refs in keymap order."""
    at = {(pos["col"], pos["row"]): ref for ref, pos in matrix.items()}
    order = []
    for key_row in range(4):
        order += [at[(key_row, finger)] for finger in range(5)]
        order += [at[(4 + key_row, finger)] for finger in reversed(range(5))]
    left_thumbs = sorted((col, ref) for (col, row), ref in at.items() if row == 5 and col < 4)
    right_thumbs = sorted(((col, ref) for (col, row), ref in at.items() if row == 5 and col >= 4), reverse=True)
    return order + [ref for _, ref in left_thumbs] + [ref for _, ref in right_thumbs]


def dt_int(value):
    return f"({value})" if value < 0 else str(value)


def physical_attrs(key):
    cu = lambda mm: round(mm / UNIT_MM * 100)
    w, h = cu(CELL_W), cu(CELL_H)
    x, y = cu(key["x"] - CELL_W / 2), cu(key["y"] - CELL_H / 2)
    rot = round(-key["rot"] * 100)
    return f"<&key_physical_attrs {w:>3} {h:>3} {x:>5} {y:>5} {dt_int(rot):>7} {cu(key['x']):>5} {cu(key['y']):>5}>"


def main():
    matrix = json.loads(MATRIX.read_text())
    keys = {key["ref"]: key for key in json.loads(LAYOUT.read_text())["keys"]}
    order = keymap_order(matrix)
    rc = [f"RC({matrix[ref]['row']},{matrix[ref]['col']})" for ref in order]
    rows = [" ".join(rc[i:i + 10]) for i in range(0, 40, 10)] + [" ".join(rc[40:])]
    attrs = [physical_attrs(keys[ref]) for ref in order]
    lines = [
        "/* Generated by tools/gen_zmk.py from board/layout.json and tools/matrix.json, do not edit. */",
        "",
        "#include <physical_layouts.dtsi>",
        "#include <dt-bindings/zmk/matrix_transform.h>",
        "",
        "/ {",
        "    default_transform: keymap_transform_0 {",
        '        compatible = "zmk,matrix-transform";',
        "        columns = <8>;",
        "        rows = <6>;",
        "        map = <",
        *[f"            {row}" for row in rows],
        "        >;",
        "    };",
        "",
        "    physical_layout0: physical_layout_0 {",
        '        compatible = "zmk,physical-layout";',
        '        display-name = "Default";',
        "        kscan = <&kscan0>;",
        "        transform = <&default_transform>;",
        "        keys  //                   w   h     x     y     rot    rx    ry",
        "            = " + "\n            , ".join(attrs),
        "            ;",
        "    };",
        "};",
        "",
    ]
    OUTPUT.parent.mkdir(parents=True, exist_ok=True)
    OUTPUT.write_text("\n".join(lines))
    print(f"{len(order)} keys -> {OUTPUT}")


if __name__ == "__main__":
    main()
